"""
Ops Audit models: AuditEvent, RequestTrace, and ApiCallRollup.

ISOLATION RULE: No imports from backend.portfolio or backend.* allowed.
"""
import uuid

from django.db import models


class AuditEvent(models.Model):
    class ActionChoices(models.TextChoices):
        CREATE = 'create', 'Create'
        UPDATE = 'update', 'Update'
        DELETE = 'delete', 'Delete'
        ACCESS = 'access', 'Access'
        AUTH = 'auth', 'Auth'
        REVOKE = 'revoke', 'Revoke'

    event_id = models.UUIDField(default=uuid.uuid4, unique=True, db_index=True, editable=False)
    actor_user_id = models.IntegerField(null=True, blank=True, db_index=True)
    actor_label = models.CharField(max_length=120, blank=True, default='')
    tenant_id = models.CharField(max_length=36, blank=True, default='', db_index=True)
    action = models.CharField(max_length=16, choices=ActionChoices.choices, db_index=True)
    resource_type = models.CharField(max_length=64, db_index=True)
    resource_id = models.CharField(max_length=64, blank=True, default='')
    request_id = models.CharField(max_length=36, blank=True, default='', db_index=True)
    pat_id = models.CharField(max_length=36, null=True, blank=True, db_index=True, verbose_name='PAT public id')
    ip_address = models.GenericIPAddressField(null=True, blank=True)
    metadata = models.JSONField(default=dict, blank=True)
    occurred_at = models.DateTimeField(auto_now_add=True, db_index=True)

    class Meta:
        verbose_name = 'Audit Event'
        verbose_name_plural = 'Audit Events'
        ordering = ['-occurred_at', '-pk']
        indexes = [
            models.Index(fields=['tenant_id', 'action', 'occurred_at']),
        ]

    def __str__(self):
        return f'[{self.action}] {self.resource_type}/{self.resource_id} by {self.actor_label}'


class RequestTrace(models.Model):
    request_id = models.CharField(max_length=36, unique=True, db_index=True)
    method = models.CharField(max_length=8)
    path = models.CharField(max_length=512)
    status_code = models.SmallIntegerField(null=True, blank=True)
    actor_user_id = models.IntegerField(null=True, blank=True)
    tenant_id = models.CharField(max_length=36, blank=True, default='')
    duration_ms = models.IntegerField(null=True, blank=True)
    traced_at = models.DateTimeField(auto_now_add=True, db_index=True)

    class Meta:
        verbose_name = 'Request Trace'
        verbose_name_plural = 'Request Traces'
        ordering = ['-traced_at', '-pk']

    def __str__(self):
        return f'{self.method} {self.path} [{self.status_code}] {self.request_id}'


class ApiCallRollup(models.Model):
    """Pre-aggregated hourly API call metrics for fast tenant analytics.

    Generated by the aggregate_api_call_rollup Celery task from AuditEvent.
    Stored at hourly granularity (hour 0-23); daily views SUM the hourly rows,
    avoiding mixed-granularity rows in one table. Group dimensions (ip_address,
    endpoint_group, status_group) always hold concrete values (never NULL) so
    unique_together is reliable and "all" aggregates are computed at query time.
    """

    tenant_id = models.CharField(max_length=36, db_index=True)
    date = models.DateField(db_index=True)
    hour = models.SmallIntegerField()  # 0-23
    ip_address = models.CharField(max_length=64, default='', db_index=True)  # actual IP or ''
    endpoint_group = models.CharField(max_length=64, default='other')
    status_group = models.CharField(max_length=8, default='2xx')  # '2xx'/'4xx'/'5xx'
    call_count = models.IntegerField(default=0)
    error_count = models.IntegerField(default=0)
    total_duration_ms = models.BigIntegerField(default=0)

    class Meta:
        verbose_name = 'API Call Rollup'
        verbose_name_plural = 'API Call Rollups'
        db_table = 'ops_audit_api_call_rollup'
        ordering = ['tenant_id', 'date', 'hour']
        unique_together = [('tenant_id', 'date', 'hour', 'ip_address', 'endpoint_group', 'status_group')]
        indexes = [
            models.Index(fields=['tenant_id', 'date', 'hour', 'ip_address'], name='ops_rollup_tnt_date_hr_ip'),
            models.Index(fields=['tenant_id', 'date', 'hour', 'endpoint_group'], name='ops_rollup_tnt_date_hr_ep'),
            models.Index(fields=['tenant_id', 'date', 'hour', 'status_group'], name='ops_rollup_tnt_date_hr_st'),
        ]

    def __str__(self):
        return f'rollup {self.tenant_id} {self.date} {self.hour:02d}h {self.endpoint_group} {self.status_group}'
