#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Bootstrap tat ca env files cho du an vninvest.

.DESCRIPTION
    Tao cac file .env tu .env.example voi secret key duoc sinh tu dong (crypto-safe).
    Idempotent: file da ton tai se bi bo qua.

    Files duoc tao:
      backend/.env      - Local dev khong Docker (DB_ENGINE=sqlite)
      backend/.env.dev  - Docker dev stack (DB_ENGINE=postgres, host=db, redis=redis)
      frontend/.env     - Frontend local dev

.USAGE
    .\scripts\dev-setup.ps1          # bootstrap lan dau
    .\scripts\dev-setup.ps1 -Force   # ghi de toan bo (ke ca file da co)
#>
param(
    [switch]$Force
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$Root        = Split-Path $PSScriptRoot -Parent
$BackendDir  = Join-Path $Root "backend"
$FrontendDir = Join-Path $Root "frontend"

function Write-Ok($msg)   { Write-Host "  [OK]   $msg" -ForegroundColor Green }
function Write-Skip($msg) { Write-Host "  [skip] $msg (da ton tai)" -ForegroundColor DarkGray }
function Write-Warn($msg) { Write-Host "  [WARN] $msg" -ForegroundColor Yellow }
function Write-Step($msg) { Write-Host ""; Write-Host "==> $msg" -ForegroundColor Cyan }

function New-DjangoSecretKey {
    $bytes = New-Object byte[] 50
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)
    $rng.Dispose()
    return [Convert]::ToBase64String($bytes) -replace '=','' -replace '\+','-' -replace '/','_'
}

function Set-EnvVar([string]$Content, [string]$Key, [string]$Value) {
    if ($Content -match "(?m)^${Key}=") {
        return $Content -replace "(?m)^${Key}=.*$", "${Key}=${Value}"
    } else {
        return $Content.TrimEnd() + "`n${Key}=${Value}"
    }
}

# 1. backend/.env  -  Local dev (SQLite)
Write-Step "backend/.env  [Local dev - SQLite, khong can Docker]"
$target   = Join-Path $BackendDir ".env"
$template = Join-Path $BackendDir ".env.example"

if ((Test-Path $target) -and (-not $Force)) {
    Write-Skip "backend/.env"
} elseif (-not (Test-Path $template)) {
    Write-Warn "backend/.env.example khong tim thay, bo qua."
} else {
    $content = Get-Content $template -Raw -Encoding UTF8
    $key     = New-DjangoSecretKey
    $content = Set-EnvVar $content "DJANGO_SECRET_KEY"     $key
    $content = Set-EnvVar $content "DB_ENGINE"              "sqlite"
    $content = Set-EnvVar $content "REALTIME_CHANNEL_LAYER" "inmemory"
    $content = Set-EnvVar $content "POSTGRES_HOST"          "localhost"
    $header  = "# Auto-generated by scripts/dev-setup.ps1 on $(Get-Date -Format 'yyyy-MM-dd')`n# DO NOT COMMIT`n`n"
    ($header + $content) | Set-Content $target -Encoding UTF8
    Write-Ok "backend/.env da tao (DB=sqlite, channel=inmemory)"
}

# 2. backend/.env.dev  -  Docker dev stack
Write-Step "backend/.env.dev  [Docker dev stack - postgres + redis service names]"
$target = Join-Path $BackendDir ".env.dev"

if ((Test-Path $target) -and (-not $Force)) {
    Write-Skip "backend/.env.dev"
} elseif (-not (Test-Path $template)) {
    Write-Warn "backend/.env.example khong tim thay, bo qua."
} else {
    $content = Get-Content $template -Raw -Encoding UTF8
    $key     = New-DjangoSecretKey
    $content = Set-EnvVar $content "DJANGO_SECRET_KEY"          $key
    $content = Set-EnvVar $content "DB_ENGINE"                   "postgres"
    $content = Set-EnvVar $content "POSTGRES_HOST"               "db"
    $content = Set-EnvVar $content "POSTGRES_PORT"               "5432"
    $content = Set-EnvVar $content "POSTGRES_DB"                 "vninvest"
    $content = Set-EnvVar $content "POSTGRES_USER"               "postgres"
    $content = Set-EnvVar $content "POSTGRES_PASSWORD"           "devpassword"
    $content = Set-EnvVar $content "CELERY_BROKER_URL"           "redis://redis:6379/0"
    $content = Set-EnvVar $content "CELERY_RESULT_BACKEND"       "redis://redis:6379/0"
    $content = Set-EnvVar $content "CACHE_REDIS_URL"             "redis://redis:6379/2"
    $content = Set-EnvVar $content "REALTIME_REDIS_URL"          "redis://redis:6379/0"
    $content = Set-EnvVar $content "REALTIME_CHANNEL_LAYER"      "redis"
    $content = Set-EnvVar $content "REALTIME_ENABLED"            "True"
    $content = Set-EnvVar $content "CORS_ALLOWED_ORIGINS"        "http://localhost:3000,http://localhost:3001,http://localhost:8080"
    $content = Set-EnvVar $content "CSRF_TRUSTED_ORIGINS"        "http://localhost:3000,http://localhost:3001,http://localhost:8080"
    $content = Set-EnvVar $content "SYSTEM_EMAIL_FALLBACK_ENABLED" "True"
    $content = Set-EnvVar $content "SYSTEM_EMAIL_FALLBACK_HOST"  "mailpit"
    $content = Set-EnvVar $content "SYSTEM_EMAIL_FALLBACK_PORT"  "1025"
    $header  = "# Auto-generated by scripts/dev-setup.ps1 on $(Get-Date -Format 'yyyy-MM-dd')`n# Docker dev stack - DO NOT COMMIT`n`n"
    ($header + $content) | Set-Content $target -Encoding UTF8
    Write-Ok "backend/.env.dev da tao (DB=postgres@db, Redis=redis, Mailpit=mailpit)"
}

# 3. frontend/.env
Write-Step "frontend/.env"
$target = Join-Path $FrontendDir ".env"
$source = Join-Path $FrontendDir ".env.example"

if ((Test-Path $target) -and (-not $Force)) {
    Write-Skip "frontend/.env"
} elseif (Test-Path $source) {
    Copy-Item $source $target -Force
    Write-Ok "frontend/.env da tao tu .env.example"
} else {
    @("REACT_APP_API_BASE_URL=/api","REACT_APP_AI_ADVISORY_PATH=/ai-advisory") | Set-Content $target -Encoding UTF8
    Write-Ok "frontend/.env da tao (hardcoded defaults)"
}

Write-Host ""
Write-Host "Bootstrap complete." -ForegroundColor Green
Write-Host "  Local dev:    cd backend; python manage.py migrate; python manage.py runserver" -ForegroundColor DarkCyan
Write-Host "  Docker stack: .\start_dev.ps1" -ForegroundColor DarkCyan
Write-Host "  Gen lai:      .\scripts\dev-setup.ps1 -Force" -ForegroundColor DarkCyan
Write-Host ""