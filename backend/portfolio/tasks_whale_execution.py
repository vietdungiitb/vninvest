from __future__ import annotations
from portfolio.tasks_whale_finalize_phase import _execute_whale_generation_finalize_phase
from portfolio.tasks_whale_persist_phase import _execute_whale_generation_persist_phase


def _execute_whale_generation_postprovider(
    *,
    symbol: str,
    matched_value_vnd: float,
    side: str,
    threshold: float,
    source: str,
    force_refresh: bool,
    user_id: int | None,
    source_key: str,
    advisory_type: str,
    severity_override: str | None,
    threshold_source: str,
    dark_flow_strength: float | None,
    dark_flow_confidence: str | None,
    latest_existing_advisory,
    target_user,
    user_cfg,
    provider: str,
    model: str,
    primary_provider: str,
    primary_model: str,
    ai_source: str,
    output_language: str,
    language_mismatch: bool,
    failover_occurred: bool,
    failover_reason: str,
    failover_chain_attempted: list[str],
    failover_attempt_count: int,
    use_concise: bool,
    cache_key: str,
    cooldown: int,
    summary_resp: dict,
    deep_resp: dict,
    merged_sources: list[str] | None,
    primary_source: str | None,
    task_id: str,
) -> dict:
    persist_result = _execute_whale_generation_persist_phase(
        symbol=symbol,
        matched_value_vnd=matched_value_vnd,
        side=side,
        threshold=threshold,
        source=source,
        force_refresh=force_refresh,
        source_key=source_key,
        advisory_type=advisory_type,
        severity_override=severity_override,
        threshold_source=threshold_source,
        dark_flow_strength=dark_flow_strength,
        dark_flow_confidence=dark_flow_confidence,
        latest_existing_advisory=latest_existing_advisory,
        target_user=target_user,
        user_cfg=user_cfg,
        provider=provider,
        model=model,
        use_concise=use_concise,
        cache_key=cache_key,
        cooldown=cooldown,
        summary_resp=summary_resp,
        deep_resp=deep_resp,
        merged_sources=merged_sources,
        primary_source=primary_source,
    )

    return _execute_whale_generation_finalize_phase(
        symbol=symbol,
        side=side,
        matched_value_vnd=matched_value_vnd,
        threshold=threshold,
        user_id=user_id,
        source_key=source_key,
        provider=provider,
        model=model,
        primary_provider=primary_provider,
        primary_model=primary_model,
        ai_source=ai_source,
        output_language=output_language,
        language_mismatch=language_mismatch,
        failover_occurred=failover_occurred,
        failover_reason=failover_reason,
        failover_chain_attempted=failover_chain_attempted,
        failover_attempt_count=failover_attempt_count,
        force_refresh=force_refresh,
        latest_existing_advisory=latest_existing_advisory,
        target_user=target_user,
        use_concise=use_concise,
        task_id=task_id,
        advisory=persist_result['advisory'],
        normalized_threshold_source=persist_result['normalized_threshold_source'],
        normalized_merged_sources=persist_result['normalized_merged_sources'],
        normalized_primary_source=persist_result['normalized_primary_source'],
    )
